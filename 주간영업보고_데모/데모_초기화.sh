#!/bin/bash
# 발표 직전 실행: 라이브 데모 초기 상태로 되돌린다.
#  1) 결과 폴더 비우기
#  2) 기존 워크북(영업관리.xlsx)을 지난주 상태로 복원
#  3) 리허설이 남긴 중간 산출물(추출 JSON 등) 제거 — 남아 있으면
#     라이브 실행 때 Codex가 추출을 건너뛰어 데모 리얼함이 사라진다.
# 백업_결과 폴더는 건드리지 않는다 (실행 실패 시 대체용).
cd "$(dirname "$0")"
rm -f 결과/*.xlsx 결과/*.docx 결과/*.pptx
rm -f ./*.json
cp 백업_결과/지난주_영업관리.xlsx 영업관리.xlsx
echo "초기화 완료."
echo "- 결과 폴더:"; ls -la 결과
echo "- 영업관리.xlsx = 지난주(7/6~7/10, 17건) 상태로 복원"
